//! Generates the engine's id constants (`MoveId::TACKLE`, `AbilityId::INTIMIDATE`,
//! `ItemId::CHOICE_BAND` …) from the id registry, `data/dex/ids.json` (DESIGN.md §27.1), with
//! each constant named after the move / ability / item's English name in the latest
//! generation that has it. Hand-numbered constants could drift from the registry; these cannot.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

const KINDS: [(&str, &str); 3] = [
    ("moves", "MoveId"),
    ("abilities", "AbilityId"),
    ("items", "ItemId"),
];

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("data/dex");
    println!("cargo:rerun-if-changed=build.rs");
    let read = |file: &str| -> Value {
        let path = root.join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        serde_json::from_str(&text).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
    };

    let registry = read("ids.json");
    // The latest generation's English name for each Showdown id.
    let mut names: BTreeMap<&str, BTreeMap<String, String>> = BTreeMap::new();
    for generation in 1..=9 {
        let snapshot = read(&format!("gen{generation}.json"));
        for (kind, _) in KINDS {
            let rows = snapshot[kind].as_array().expect("snapshot rows");
            let names = names.entry(kind).or_default();
            for row in rows {
                let id = row["id"].as_str().expect("id").to_owned();
                let name = row["name"].as_str().expect("name").to_owned();
                names.insert(id, name);
            }
        }
    }

    let mut out = String::from("// Generated by build.rs from data/dex/ids.json. Do not edit.\n");
    for (kind, rust_type) in KINDS {
        let entries = registry[kind].as_object().expect("registry kind");
        let mut constants: BTreeMap<String, (String, u64, String)> = BTreeMap::new();
        for (id, entry) in entries {
            let eid = entry["eid"].as_u64().expect("eid");
            let name = names[kind].get(id).cloned().unwrap_or_else(|| id.clone());
            let constant = constant_name(&name);
            if let Some((other, ..)) = constants.get(&constant) {
                panic!("{kind}: `{constant}` would name both `{other}` and `{id}`");
            }
            constants.insert(constant, (id.clone(), eid, name));
        }
        writeln!(out, "\nimpl {rust_type} {{").unwrap();
        for (constant, (id, eid, name)) in constants {
            writeln!(out, "    /// {name} (Showdown `{id}`).").unwrap();
            writeln!(out, "    pub const {constant}: Self = Self({eid});").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }

    // Species (`SpeciesId { dex, form }`): named after the latest generation's name for the id.
    let mut species_names: BTreeMap<String, String> = BTreeMap::new();
    for generation in 1..=9 {
        let snapshot = read(&format!("gen{generation}.json"));
        for row in snapshot["species"].as_array().expect("species rows") {
            let id = row["id"].as_str().expect("id").to_owned();
            species_names.insert(id, row["name"].as_str().expect("name").to_owned());
        }
    }
    let mut constants: BTreeMap<String, (String, u64, u64, String)> = BTreeMap::new();
    for (id, entry) in registry["species"].as_object().expect("species registry") {
        let dex = entry["dex"].as_u64().expect("dex");
        let form = entry["form"].as_u64().expect("form");
        let name = species_names.get(id).cloned().unwrap_or_else(|| id.clone());
        let constant = constant_name(&name);
        if let Some((other, ..)) = constants.get(&constant) {
            panic!("species: `{constant}` would name both `{other}` and `{id}`");
        }
        constants.insert(constant, (id.clone(), dex, form, name));
    }
    writeln!(out, "\nimpl SpeciesId {{").unwrap();
    for (constant, (id, dex, form, name)) in constants {
        writeln!(out, "    /// {name} (Showdown `{id}`).").unwrap();
        writeln!(
            out,
            "    pub const {constant}: Self = Self {{ dex: {dex}, form: {form} }};"
        )
        .unwrap();
    }
    writeln!(out, "}}").unwrap();

    let target = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("ids.rs");
    std::fs::write(&target, out).unwrap_or_else(|error| panic!("{}: {error}", target.display()));
}

/// `King's Shield` → `KINGS_SHIELD`, `U-turn` → `U_TURN`, `As One (Glastrier)` →
/// `AS_ONE_GLASTRIER`; a name that starts with a digit gets an `N` (`10,000,000 Volt
/// Thunderbolt` → `N10_000_000_VOLT_THUNDERBOLT`).
fn constant_name(name: &str) -> String {
    let mut out = String::new();
    let mut separator = false;
    for ch in name.chars() {
        if ch == '\'' {
            continue;
        }
        if ch.is_ascii_alphanumeric() {
            if separator && !out.is_empty() {
                out.push('_');
            }
            separator = false;
            out.push(ch.to_ascii_uppercase());
        } else {
            separator = true;
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'N');
    }
    out
}
