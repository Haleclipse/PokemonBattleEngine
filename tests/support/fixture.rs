use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Provenance {
    pub showdown: Option<SourceVersion>,
    pub damage: Option<SourceVersion>,
    pub data: Option<SourceVersion>,
    #[serde(default)]
    pub references: Vec<Reference>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct SourceVersion {
    pub name: String,
    pub version: String,
    #[serde(default)]
    pub revision: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct Reference {
    pub kind: String,
    pub locator: String,
    #[serde(default)]
    pub note: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct FixtureManifest {
    pub schema: u32,
    pub oracle_schema: u32,
    pub provenance: Provenance,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CoverageLedger {
    pub schema: u32,
    pub mechanics: Vec<MechanicCoverage>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct MechanicCoverage {
    pub id: String,
    pub status: CoverageStatus,
    pub generations: Vec<u8>,
    #[serde(default)]
    pub singles: bool,
    #[serde(default)]
    pub doubles: bool,
    #[serde(default)]
    pub local_tests: Vec<String>,
    #[serde(default)]
    pub oracles: Vec<String>,
    #[serde(default)]
    pub references: Vec<String>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum CoverageStatus {
    Planned,
    Partial,
    Verified,
}

pub fn load_json<T: for<'de> Deserialize<'de>>(path: &std::path::Path) -> T {
    let content = std::fs::read_to_string(path)
        .unwrap_or_else(|error| panic!("failed to read {}: {error}", path.display()));
    serde_json::from_str(&content)
        .unwrap_or_else(|error| panic!("failed to parse {}: {error}", path.display()))
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EngineProvenance {
    pub engine: String,
    pub version: String,
}

/// `tests/fixtures/oracle/damage-expected.json`: hand-written cases plus the `@smogon/calc`
/// rolls generated by `tools/gen-damage-fixtures.py`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DamageExpectations {
    pub schema: u32,
    pub provenance: EngineProvenance,
    pub cases: Vec<DamageCase>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DamageCase {
    pub id: String,
    pub generation: u8,
    pub mode: String,
    pub attacker: DamageSide,
    pub defender: DamageSide,
    #[serde(rename = "move")]
    pub move_name: String,
    #[serde(default)]
    pub field: DamageField,
    pub expected: DamageExpected,
    #[serde(default)]
    pub description: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DamageSide {
    pub level: u8,
    pub stats: StatsRow,
    pub types: Vec<String>,
    #[serde(default)]
    pub ability: Option<String>,
    #[serde(default)]
    pub item: Option<String>,
    #[serde(default)]
    pub status: Option<String>,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub struct StatsRow {
    pub hp: u16,
    pub atk: u16,
    pub def: u16,
    pub spa: u16,
    pub spd: u16,
    pub spe: u16,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize, PartialEq, Eq)]
pub struct DamageField {
    #[serde(default)]
    pub weather: Option<String>,
    #[serde(default)]
    pub terrain: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DamageExpected {
    /// One value per damage roll 85..=100, ascending.
    pub damage: Vec<u16>,
    pub range: [u16; 2],
}

/// `tests/fixtures/oracle/stats-expected.json`: stat-formula cases with `@smogon/calc` results.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct StatsExpectations {
    pub schema: u32,
    pub provenance: EngineProvenance,
    pub cases: Vec<StatsCase>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct StatsCase {
    pub id: String,
    pub generation: u8,
    pub species: String,
    pub level: u8,
    #[serde(default)]
    pub nature: Option<String>,
    pub expected: StatsExpected,
    pub calc_inputs: StatsCalcInputs,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct StatsExpected {
    pub raw_stats: StatsRow,
    pub max_hp: u16,
}

/// What calc actually used after applying its defaults (0 EV / 31 IV in Gen 3+, max in Gen 1–2).
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct StatsCalcInputs {
    pub evs: StatsRow,
    pub ivs: StatsRow,
    pub nature: String,
    pub level: u8,
}

/// `data/dex/crosscheck-pokeapi.json`: PokéAPI's view of species and moves, keyed by Showdown id.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct PokeapiCrosscheck {
    pub schema: u32,
    pub species: std::collections::BTreeMap<String, CrosscheckSpecies>,
    pub moves: std::collections::BTreeMap<String, CrosscheckMove>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CrosscheckSpecies {
    pub dex: u16,
    pub types: Vec<String>,
    pub base_stats: std::collections::BTreeMap<String, u16>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct CrosscheckMove {
    #[serde(rename = "type")]
    pub type_name: String,
    pub category: String,
    pub bp: u16,
    #[serde(default)]
    pub acc: Option<u8>,
    pub pp: u8,
    pub pri: i8,
}
