/// King's Rock / Razor Fang (`ItemMoveEdit::adds_flinch`): which of the holder's moves get the
/// extra flinch chance, how likely it is, and whether Serene Grace doubles it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ItemFlinchRules {
    /// Gen 2-4: only these moves; Gen 5+ (`None`): every damaging move without a flinch chance
    /// of its own (Showdown's `onModifyMove`).
    pub moves: Option<&'static [MoveId]>,
    /// Gen 2: 12 % (the byte 30 of 256, the cartridge's parameter); then 10 %.
    pub chance_percent: u8,
    /// Serene Grace doubles it. Gen 3-4: no — the cartridge rolls the item on its own
    /// (`Random() % 100 < 10`: pokeemerald `ITEMEFFECT_KINGSROCK_SHELLBELL`, pokeplatinum
    /// `CheckExtraFlinch`), where Showdown adds it to the move's secondaries before Serene Grace
    /// doubles them (issues.md I12). Gen 5+: yes, as Showdown (issues.md I13).
    pub doubled_by_serene_grace: bool,
}

impl ItemFlinchRules {
    pub(crate) const fn for_generation(generation: Generation) -> Self {
        match generation {
            Generation::Gen1 | Generation::Gen2 => Self {
                moves: Some(GEN2_ITEM_FLINCH_MOVES),
                chance_percent: 12,
                doubled_by_serene_grace: false,
            },
            Generation::Gen3 => Self {
                moves: Some(GEN3_ITEM_FLINCH_MOVES),
                chance_percent: 10,
                doubled_by_serene_grace: false,
            },
            Generation::Gen4 => Self {
                moves: Some(GEN4_ITEM_FLINCH_MOVES),
                chance_percent: 10,
                doubled_by_serene_grace: false,
            },
            _ => Self {
                moves: None,
                chance_percent: 10,
                doubled_by_serene_grace: true,
            },
        }
    }
}
